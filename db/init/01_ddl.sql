-- =====================================================================
-- OptiRoute & CoreDB  ::  01 DDL  (Data Definition Language)
-- Creates the core relational schema with explicit integrity constraints.
-- Runs automatically on first boot of the Oracle XE container.
-- =====================================================================
ALTER SESSION SET CONTAINER = XEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = OPTIROUTE;
SET DEFINE OFF;
SET SERVEROUTPUT ON;

-- ---------------------------------------------------------------- warehouses
CREATE TABLE warehouses (
  warehouse_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR2(120) NOT NULL,
  x_coord      NUMBER(10,2)  NOT NULL,
  y_coord      NUMBER(10,2)  NOT NULL,
  capacity_kg  NUMBER(12,2)  DEFAULT 1000 NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_warehouse_capacity CHECK (capacity_kg > 0),
  CONSTRAINT uq_warehouse_name     UNIQUE (name)
);

-- ------------------------------------------------------------ transit_routes
CREATE TABLE transit_routes (
  route_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id   NUMBER NOT NULL,
  dest_id     NUMBER NOT NULL,
  distance_km NUMBER(10,2) NOT NULL,
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_route_source FOREIGN KEY (source_id)
      REFERENCES warehouses (warehouse_id) ON DELETE CASCADE,
  CONSTRAINT fk_route_dest FOREIGN KEY (dest_id)
      REFERENCES warehouses (warehouse_id) ON DELETE CASCADE,
  CONSTRAINT ck_route_distance CHECK (distance_km > 0),
  CONSTRAINT ck_route_distinct CHECK (source_id <> dest_id),
  CONSTRAINT uq_route UNIQUE (source_id, dest_id)
);

-- ------------------------------------------------------------------ packages
CREATE TABLE packages (
  package_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           VARCHAR2(40) NOT NULL,
  description    VARCHAR2(200),
  weight_kg      NUMBER(10,2) NOT NULL,
  declared_value NUMBER(12,2) NOT NULL,
  priority       NUMBER(1)    NOT NULL,
  status         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  warehouse_id   NUMBER,
  created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_package_code      UNIQUE (code),
  CONSTRAINT fk_package_warehouse FOREIGN KEY (warehouse_id)
      REFERENCES warehouses (warehouse_id) ON DELETE SET NULL,
  CONSTRAINT ck_package_weight    CHECK (weight_kg > 0),
  CONSTRAINT ck_package_value     CHECK (declared_value >= 0),
  CONSTRAINT ck_package_priority  CHECK (priority BETWEEN 1 AND 5),
  CONSTRAINT ck_package_status    CHECK (status IN
      ('PENDING','PROCESSING','DISPATCHED','DELIVERED','CANCELLED'))
);

-- ---------------------------------------------------------- operational_logs
CREATE TABLE operational_logs (
  log_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  package_id NUMBER,
  action     VARCHAR2(40) NOT NULL,
  payload    CLOB,
  logged_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_log_package FOREIGN KEY (package_id)
      REFERENCES packages (package_id) ON DELETE SET NULL
);

-- ------------------------------------------------------------- support index
CREATE INDEX ix_routes_source ON transit_routes (source_id);
CREATE INDEX ix_packages_status ON packages (status);
CREATE INDEX ix_logs_package ON operational_logs (package_id);

PROMPT [01_ddl] core schema created.
